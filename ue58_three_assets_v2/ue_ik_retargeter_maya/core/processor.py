# -*- coding: utf-8 -*-
"""
Main retarget processor coordinating pelvis, FK chains, IK goals, and the 3 UE 5.8 standard assets:
1. IK_AutoGeneratedSource (UIKRigDefinition)
2. IK_AutoGeneratedTarget (UIKRigDefinition)
3. RTG_AutoGenerated      (UIKRetargeter)

Directly implements UE 5.8's FIKRetargetProcessor (IKRetargetProcessor.cpp)
and SRetargetAnimAssetsWindow::ExportRetargetAssets.
100% Immune to duplicate joint names ("注意重名") via full Maya DAG paths.
"""

import os
import json
import maya.cmds as cmds
import maya.api.OpenMaya as om

from .skeleton import RetargetSkeleton, resolve_skeleton_root_joint
from .chains import BoneChain, ChainMapping, AutoCharacterizer, CHAIN_PATTERNS
from .retarget_pose import RetargetPoseManager
from .pelvis_solver import PelvisMotionSolver
from .fk_solver import FKChainSolver
from .ik_solver import IKChainSolver, TwoBoneIKSolver
from .auto_align import AutoPoseAligner
from .retarget_assets import (
    IKRigAsset,
    IKRetargeterAsset,
    MayaSceneAssetBuilder,
    derive_unique_skeleton_tags,
    _quat_to_deg_list,
)
from .math_utils import set_world_transform, get_world_transform


class IKRetargetProcessor(object):
    """
    Master processor that characterizes Source A and Target B into UE 5.8 standard
    IKRigDefinitions + IKRetargeter, aligns base poses, and retargets animation.
    """

    def __init__(self, source_root, target_root, source_pelvis=None, target_pelvis=None):
        src_resolved = resolve_skeleton_root_joint(source_root) or source_root
        tgt_resolved = resolve_skeleton_root_joint(target_root) or target_root

        # Initialize Skeletons (all joints stored as full DAG paths '|...')
        self.source_skeleton = RetargetSkeleton(src_resolved)
        self.target_skeleton = RetargetSkeleton(tgt_resolved)

        self.source_root = self.source_skeleton.root_joint
        self.target_root = self.target_skeleton.root_joint

        if self.source_root == self.target_root:
            raise RuntimeError(
                "Source A and Target B resolved to the exact same skeleton root joint: {}\n"
                "Please select two distinct skeletons (A and B) in the Maya scene.".format(self.source_root)
            )

        self.source_pelvis = (
            self.source_skeleton.resolve_bone_dag(source_pelvis)
            if source_pelvis else self.source_root
        )
        self.target_pelvis = (
            self.target_skeleton.resolve_bone_dag(target_pelvis)
            if target_pelvis else self.target_root
        )

        # Pose managers for Source and Target Retarget Poses
        self.source_pose_mgr = RetargetPoseManager(self.source_skeleton, pose_name="DefaultRetargetPose")
        self.target_pose_mgr = RetargetPoseManager(self.target_skeleton, pose_name="DefaultRetargetPose")

        # Characterization profiles & 3 Standard UE 5.8 Assets
        self.source_profile = None
        self.target_profile = None
        self.bones_to_exclude_from_auto_pose = []

        self.source_ikrig_asset = None
        self.target_ikrig_asset = None
        self.rtg_asset = None

        # Solvers
        self.pelvis_solver = None
        self.chain_mappings = []
        self.fk_solvers = []
        self.ik_solvers = []

        # Auto-characterize chains, auto-align base pose, and build 3 asset objects
        self.setup_default_chains()

    def setup_default_chains(self):
        """
        Discovers standard UE 5.8 chains (21+ chains including Spine, Neck, Head, Clavicles,
        Arms, Legs, Feet, and 10 Fingers), auto-aligns base pose, and initializes solvers.
        """
        self.auto_map_chains()
        self.auto_align_base_pose()
        self.update_retarget_poses()
        self._rebuild_asset_definitions()

    def _rebuild_asset_definitions(self):
        """Updates the 3 standard UE 5.8 asset objects (`IK_AutoGeneratedSource`, `IK_AutoGeneratedTarget`, `RTG_AutoGenerated`)."""
        src_tag, tgt_tag = derive_unique_skeleton_tags(self.source_skeleton, self.target_skeleton)

        src_asset_name = "IK_AutoGeneratedSource_{}".format(src_tag)
        tgt_asset_name = "IK_AutoGeneratedTarget_{}".format(tgt_tag)
        rtg_asset_name = "RTG_AutoGenerated_{}_to_{}".format(src_tag, tgt_tag)

        self.source_ikrig_asset = IKRigAsset(
            src_asset_name, "Source", self.source_skeleton, self.source_profile
        )
        self.target_ikrig_asset = IKRigAsset(
            tgt_asset_name, "Target", self.target_skeleton, self.target_profile
        )
        self.rtg_asset = IKRetargeterAsset(
            rtg_asset_name, self.source_ikrig_asset, self.target_ikrig_asset, self
        )

    def update_retarget_poses(self):
        """Refreshes all solvers when the retarget base pose is aligned or modified."""
        if self.pelvis_solver:
            self.pelvis_solver.update_retarget_pose()
        for fk in self.fk_solvers:
            fk.update_retarget_pose()
        for ik in self.ik_solvers:
            ik.update_retarget_pose()

    def auto_map_chains(self):
        """
        Runs UE 5.8 AutoCharacterizer on Source A and Target B, pairs all matching
        BoneChains, configures PelvisMotionSolver, and sets up FK/IK solvers.
        """
        self.chain_mappings = []
        self.fk_solvers = []
        self.ik_solvers = []

        self.source_profile = AutoCharacterizer.characterize(self.source_skeleton)
        self.target_profile = AutoCharacterizer.characterize(self.target_skeleton)

        if self.source_profile.get("pelvis_bone_dag"):
            self.source_pelvis = self.source_profile["pelvis_bone_dag"]
        if self.target_profile.get("pelvis_bone_dag"):
            self.target_pelvis = self.target_profile["pelvis_bone_dag"]

        self.bones_to_exclude_from_auto_pose = list(
            self.target_profile.get("bones_to_exclude_from_auto_pose", [])
        )

        self.pelvis_solver = PelvisMotionSolver(
            self.source_pelvis,
            self.target_pelvis,
            self.source_skeleton,
            self.target_skeleton,
            self.target_pose_mgr,
        )

        src_chains_dict = self.source_profile.get("bone_chains", {})
        tgt_chains_dict = self.target_profile.get("bone_chains", {})

        # Map all chains in Target B that have a corresponding chain in Source A
        for c_info in self.target_profile.get("chains", []):
            cname = c_info["chain_name"]
            if cname in src_chains_dict and cname in tgt_chains_dict:
                src_chain = src_chains_dict[cname]
                tgt_chain = tgt_chains_dict[cname]
                ik_goal_name = c_info.get("ik_goal_name", "")
                enable_ik = bool(ik_goal_name)
                self.add_chain_mapping(
                    cname,
                    src_chain.start_bone,
                    src_chain.end_bone,
                    tgt_chain.start_bone,
                    tgt_chain.end_bone,
                    enable_ik=enable_ik,
                    ik_goal_name=ik_goal_name,
                )

    def auto_align_base_pose(self):
        """
        Automatically aligns Target B's Retarget Pose to match Source A's reference pose
        using UE 5.8's per-bone topological ChainToChain tangent alignment + SnapToGround.
        """
        AutoPoseAligner.align_chains(self)
        if self.source_profile and self.target_profile:
            self._rebuild_asset_definitions()

    def add_chain_mapping(self, name, src_start, src_end, tgt_start, tgt_end, enable_ik=False, ik_goal_name=""):
        """Adds a retarget chain mapping between source and target joints."""
        src_start_dag = self.source_skeleton.resolve_bone_dag(src_start) or src_start
        src_end_dag = self.source_skeleton.resolve_bone_dag(src_end) or src_end
        tgt_start_dag = self.target_skeleton.resolve_bone_dag(tgt_start) or tgt_start
        tgt_end_dag = self.target_skeleton.resolve_bone_dag(tgt_end) or tgt_end

        if not (cmds.objExists(src_start_dag) and cmds.objExists(src_end_dag) and
                cmds.objExists(tgt_start_dag) and cmds.objExists(tgt_end_dag)):
            return False

        src_chain = BoneChain(name, src_start_dag, src_end_dag, self.source_skeleton, ik_goal_name=ik_goal_name)
        tgt_chain = BoneChain(name, tgt_start_dag, tgt_end_dag, self.target_skeleton, ik_goal_name=ik_goal_name)

        mapping = ChainMapping(name, src_chain, tgt_chain, enable_ik=enable_ik, ik_goal_name=ik_goal_name)
        self.chain_mappings.append(mapping)

        fk_solv = FKChainSolver(mapping, self.target_pose_mgr, self.source_pose_mgr)
        self.fk_solvers.append(fk_solv)

        if enable_ik and len(tgt_chain.bones) >= 3:
            ik_solv = IKChainSolver(mapping, self.target_pose_mgr, self.source_pose_mgr)
            self.ik_solvers.append(ik_solv)

        return True

    def retarget_frame(self):
        """
        Executes complete UE 5.8 retarget pipeline for current frame:
        1. Samples animated source global pose.
        2. Solves PelvisMotionOp (scaled translation + world delta rotation).
        3. Solves FKChainsOp in topological parent-to-child order (including fingers & toes).
        4. Solves IKChainsOp + Two-Bone IK + AlignPoleVectorOp on limbs.
        """
        src_pose = self.source_skeleton.get_current_pose()
        src_pelvis_pos, src_pelvis_rot = src_pose[self.source_pelvis]

        # Step 1: PelvisMotionOp
        tgt_pelvis_pos, tgt_pelvis_rot = self.pelvis_solver.solve(src_pelvis_pos, src_pelvis_rot)
        set_world_transform(self.target_pelvis, tgt_pelvis_pos, tgt_pelvis_rot)

        rest_pelvis_pos = self.target_pose_mgr.get_aligned_rest_position(self.target_pelvis)
        pelvis_translation_delta = tgt_pelvis_pos - rest_pelvis_pos

        tgt_pose_dict = {
            self.target_pelvis: (tgt_pelvis_pos, tgt_pelvis_rot)
        }

        # Step 2: FKChainsOp in topological order
        for fk_solv in self.fk_solvers:
            chain_rotations = fk_solv.solve(src_pose, target_current_pose_dict=tgt_pose_dict)
            for tgt_joint in fk_solv.tgt_chain.bones:
                if tgt_joint in chain_rotations:
                    rot = chain_rotations[tgt_joint]
                    set_world_transform(tgt_joint, quat=rot)
                    pos, _ = get_world_transform(tgt_joint)
                    tgt_pose_dict[tgt_joint] = (pos, rot)

        # Step 3: IKChainsOp + RunIKRigOp + AlignPoleVectorOp
        for ik_solv in self.ik_solvers:
            tgt_chain = ik_solv.tgt_chain
            if len(tgt_chain.bones) < 3:
                continue

            root_bone = tgt_chain.bones[0]
            mid_bone = tgt_chain.bones[1]
            end_bone = tgt_chain.bones[2]

            tgt_start_pos, current_root_rot = get_world_transform(root_bone)
            current_mid_pos, current_mid_rot = get_world_transform(mid_bone)
            current_end_pos, current_end_rot = get_world_transform(end_bone)

            goal_pos, goal_rot = ik_solv.calculate_goal_transform(
                src_pose, tgt_start_pos, pelvis_translation_delta=pelvis_translation_delta
            )

            p0 = self.target_pose_mgr.get_aligned_rest_position(root_bone)
            p1 = self.target_pose_mgr.get_aligned_rest_position(mid_bone)
            p2 = self.target_pose_mgr.get_aligned_rest_position(end_bone)
            len1 = (p1 - p0).length()
            len2 = (p2 - p1).length()

            src_root_b = ik_solv.src_chain.bones[0]
            src_mid_b = ik_solv.src_chain.bones[1]
            src_end_b = ik_solv.src_chain.bones[2]
            src_p0, _ = src_pose[src_root_b]
            src_p1, _ = src_pose[src_mid_b]
            src_p2, _ = src_pose[src_end_b]

            src_limb_vec = src_p2 - src_p0
            src_limb_axis = src_limb_vec.normal() if src_limb_vec.length() > 1e-4 else om.MVector(0, -1, 0)
            src_mid_delta = src_p1 - src_p0
            src_bend_dir = src_mid_delta - src_limb_axis * (src_mid_delta * src_limb_axis)

            if src_bend_dir.length() > 1e-4:
                pv_target = tgt_start_pos + src_bend_dir.normal() * len1
            else:
                pv_target = current_mid_pos

            is_leg = ("leg" in ik_solv.mapping.name.lower()) or ("foot" in end_bone.lower())
            end_rot_blend = 1.0 if is_leg else 0.0

            rot_upper, rot_lower, rot_end, _, _ = TwoBoneIKSolver.solve(
                tgt_start_pos, current_mid_pos, current_end_pos,
                current_root_rot, current_mid_rot, current_end_rot,
                goal_pos, goal_rot,
                pv_target,
                len1, len2,
                end_rot_blend=end_rot_blend
            )

            set_world_transform(root_bone, quat=rot_upper)
            set_world_transform(mid_bone, quat=rot_lower)
            set_world_transform(end_bone, quat=rot_end)

    def bake_animation(self, start_frame, end_frame, step=1, target_controls=None):
        """Bakes retargeted animation across the specified frame range."""
        keys_target = target_controls if target_controls else self.target_skeleton.joint_names

        orig_time = cmds.currentTime(q=True)
        try:
            for frame in range(int(start_frame), int(end_frame) + 1, int(step)):
                cmds.currentTime(frame, e=True)
                self.retarget_frame()

                for node in keys_target:
                    cmds.setKeyframe(node, time=frame, attribute=['translate', 'rotate'])
        finally:
            cmds.currentTime(orig_time, e=True)

    def generate_three_assets(
        self,
        output_dir=None,
        build_in_scene=True,
        apply_aligned_pose=True,
    ):
        """
        Generates the 3 UE 5.8 standard retarget assets:
          1. IK_AutoGeneratedSource_<SrcTag> (.ikrig.json + Maya Outliner node)
          2. IK_AutoGeneratedTarget_<TgtTag> (.ikrig.json + Maya Outliner node)
          3. RTG_AutoGenerated_<SrcTag>_to_<TgtTag> (.rtg.json + Maya Outliner node)
        """
        self._rebuild_asset_definitions()

        if output_dir is None:
            scene_path = cmds.file(q=True, sceneName=True)
            if scene_path:
                output_dir = os.path.join(os.path.dirname(scene_path), "retarget_assets")
            else:
                pkg_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                output_dir = os.path.join(pkg_root, "retarget_assets")

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        src_json_path = os.path.join(output_dir, self.source_ikrig_asset.asset_name + ".ikrig.json")
        tgt_json_path = os.path.join(output_dir, self.target_ikrig_asset.asset_name + ".ikrig.json")
        rtg_json_path = os.path.join(output_dir, self.rtg_asset.asset_name + ".rtg.json")

        with open(src_json_path, "w", encoding="utf-8") as f:
            json.dump(self.source_ikrig_asset.to_dict(), f, indent=2, ensure_ascii=False)
        with open(tgt_json_path, "w", encoding="utf-8") as f:
            json.dump(self.target_ikrig_asset.to_dict(), f, indent=2, ensure_ascii=False)
        with open(rtg_json_path, "w", encoding="utf-8") as f:
            json.dump(self.rtg_asset.to_dict(), f, indent=2, ensure_ascii=False)

        scene_nodes = {}
        if build_in_scene:
            scene_nodes = MayaSceneAssetBuilder.build_in_scene(
                processor=self,
                src_ikrig_asset=self.source_ikrig_asset,
                tgt_ikrig_asset=self.target_ikrig_asset,
                rtg_asset=self.rtg_asset,
                src_json_path=src_json_path,
                tgt_json_path=tgt_json_path,
                rtg_json_path=rtg_json_path,
                apply_aligned_pose_to_target=apply_aligned_pose,
            )

        self.print_asset_verification_report(src_json_path, tgt_json_path, rtg_json_path, scene_nodes)

        return {
            "processor": self,
            "scene_nodes": scene_nodes,
            "files": {
                "IK_AutoGeneratedSource": src_json_path,
                "IK_AutoGeneratedTarget": tgt_json_path,
                "RTG_AutoGenerated": rtg_json_path,
            },
        }


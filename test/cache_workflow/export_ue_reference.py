"""Run in UE Python: snapshot RTG settings and sample the same shopping clip.

Only a transient RTG copy and a uniquely named temporary animation are used.
The original retargeter and animation assets are never saved.
"""
import json
import traceback
import uuid
from pathlib import Path
import unreal

HERE = Path(__file__).parent
report = {'engine_version': unreal.SystemLibrary.get_engine_version()}
asset_path = '/Game/测试/woman/RTG_AutoGenerated.RTG_AutoGenerated'
animation_path = '/Game/测试/anim_Libr/studio_mocap_shopping/A_shop_sales_walkintro_f'
asset = unreal.load_asset(asset_path)
controller = unreal.IKRetargeterController.get_controller(asset)

def value(v):
    if isinstance(v, (bool, int, float, str)): return v
    if isinstance(v, unreal.Vector): return [v.x, v.y, v.z]
    if isinstance(v, unreal.Quat): return [v.x, v.y, v.z, v.w]
    if isinstance(v, unreal.Rotator): return value(v.quaternion())
    if 'BoneReference' in type(v).__name__: return str(v.get_editor_property('bone_name'))
    return str(v)

def fields(obj, names):
    return {n: value(obj.get_editor_property(n)) for n in names}

def pose_transform(t):
    return fields(t, ['translation', 'rotation', 'scale3d'])

try:
    fixture = json.loads((HERE.parent/'fixtures/pbik_cc4_mixamo.json').read_text())
    fixture['Source']['names']=['CC_Base_'+n for n in fixture['Source']['names']]
    profile = {'asset': asset_path, 'engine_version': report['engine_version'], 'ops': [], 'poses': {}, 'chains': {}}
    sides = [('Source', unreal.RetargetSourceOrTarget.SOURCE), ('Target', unreal.RetargetSourceOrTarget.TARGET)]
    meshes = {}
    for role, side in sides:
        meshes[role] = controller.get_preview_mesh(side)
        rig = unreal.IKRigController.get_controller(controller.get_ik_rig(side))
        profile['chains'][role] = [fields(c, ['chain_name','start_bone','end_bone','ik_goal_name']) for c in rig.get_retarget_chains()]
        offsets = {}
        for name in fixture[role]['names']:
            q = controller.get_rotation_offset_for_retarget_pose_bone(name, side)
            if max(abs(q.x), abs(q.y), abs(q.z)) > 1e-10: offsets[name] = value(q)
        profile['poses'][role] = {'name': str(controller.get_current_retarget_pose_name(side)),
            'root_translation_offset': value(controller.get_root_offset_in_retarget_pose(side)), 'local_rotation_offsets': offsets}
    for i in range(controller.get_num_retarget_ops()):
        op = controller.get_op_controller(i)
        settings = op.get_settings()
        entry = {'name': str(controller.get_op_name(i)), 'type': op.get_class().get_name(),
            'enabled': controller.get_retarget_op_enabled(i)}
        if 'Pelvis' in entry['type']:
            entry['settings'] = fields(settings, ['blend_to_absolute_offset','floor_constraint_weight','source_crotch_offset',
                'target_crotch_offset','use_ground_falloff','ground_falloff_height_percent','rotation_alpha','rotation_offset_local',
                'rotation_offset_global','translation_alpha','translation_offset_local','translation_offset_global',
                'blend_to_source_translation','blend_to_source_translation_weights','scale_horizontal','scale_vertical',
                'affect_ik_horizontal','affect_ik_vertical'])
        if 'FKChains' in entry['type']:
            entry['chains'] = [fields(c, ['target_chain_name','enable_fk','rotation_mode','rotation_alpha',
                'translation_mode','translation_alpha']) for c in settings.get_editor_property('chains_to_retarget')]
            entry['mapping'] = {c['chain_name']: str(controller.get_source_chain(c['chain_name'], entry['name'])) for c in profile['chains']['Target']}
        if 'RunIKRig' in entry['type']:
            entry['chains'] = [fields(c, ['target_chain_name','enable_ik','chain_position_alpha','chain_rotation_alpha',
                'override_goal_alpha','final_position_alpha','final_rotation_alpha']) for c in settings.get_editor_property('chains')]
        profile['ops'].append(entry)
    (HERE/'ue_profile.json').write_text(json.dumps(profile, ensure_ascii=False, indent=2), encoding='utf-8')
    report['profile'] = True
    animation = unreal.load_asset(animation_path)
    report['animation'] = animation_path
    report['animation_import'] = list(animation.get_editor_property('asset_import_data').extract_filenames())
    report['animation_length'] = animation.get_editor_property('sequence_length')
    # The batch operation internally overrides rig references. Use a transient
    # copy to keep the user's live RTG editor settings intact.
    temporary_path = '/Game/__CodexReference_'+uuid.uuid4().hex[:8]
    copy = unreal.EditorAssetLibrary.duplicate_asset(asset_path, temporary_path+'/ReferenceRTG')
    results = []
    try:
        results = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
            [unreal.EditorAssetLibrary.find_asset_data(animation_path)], meshes['Source'], meshes['Target'],
            copy, '', '', 'Reference_', '', temporary_path, False, False, False)
        if len(results) != 1: raise RuntimeError('Expected one retargeted animation, got '+str(len(results)))
        target_animation = results[0].get_asset()
        frames = [0, 30, 60, 90, 120, 160, 200, 240, 300, 360, 403]
        report['frames'] = {}
        for role, clip in [('Source', animation), ('Target', target_animation)]:
            options = unreal.AnimPoseEvaluationOptions()
            options.set_editor_property('optional_skeletal_mesh', meshes[role])
            options.set_editor_property('evaluation_type', unreal.AnimDataEvalType.RAW)
            report['frames'][role] = {}
            reference_pose=unreal.AnimPoseExtensions.get_anim_pose_at_frame(clip,0,options)
            profile.setdefault('reference_poses',{})[role]={name:pose_transform(
                unreal.AnimPoseExtensions.get_ref_bone_pose(reference_pose,name,unreal.AnimPoseSpaces.WORLD)) for name in fixture[role]['names']}
            for frame in frames:
                pose = unreal.AnimPoseExtensions.get_anim_pose_at_frame(clip, frame, options)
                report['frames'][role][str(frame)] = {name: pose_transform(unreal.AnimPoseExtensions.get_bone_pose(pose, name, unreal.AnimPoseSpaces.WORLD)) for name in fixture[role]['names']}
        report['golden'] = True
        (HERE/'ue_profile.json').write_text(json.dumps(profile,ensure_ascii=False,indent=2),encoding='utf-8')
    finally:
        for result in results:
            unreal.EditorAssetLibrary.delete_asset(result.get_asset().get_path_name())
        unreal.EditorAssetLibrary.delete_asset(copy.get_path_name())
        report['temporary_assets_deleted'] = not unreal.EditorAssetLibrary.list_assets(temporary_path, recursive=True)
except Exception:
    report['error'] = traceback.format_exc()
finally:
    (HERE/'ue_reference.json').write_text(json.dumps(report, ensure_ascii=False, indent=2, default=str), encoding='utf-8')
    unreal.log('CODEX_UE_REFERENCE '+json.dumps({k:v for k,v in report.items() if k!='frames'}))

"""Read a temporary copy of the saved package; preserve live unsaved edits."""
import hashlib
import json
import runpy
from pathlib import Path
import unreal

content=Path(unreal.Paths.project_content_dir()).resolve()
source=content/'测试'/'woman'/'RTG_AutoGenerated.uasset'
directory=content/'__CodexRTGReadCopy'
assert directory.parent==content and not directory.exists()
original=source.read_bytes()
saved_path='/Game/__CodexRTGReadCopy/RTG_AutoGenerated.RTG_AutoGenerated'
directory.mkdir()
copy=directory/'RTG_AutoGenerated.uasset'
copy.write_bytes(original)
try:
    runpy.run_path(str(Path(__file__).with_name('inspect_ue_retargeter.py')),
                   init_globals={'asset_override':saved_path,'output_name':'ue_saved_retarget_snapshot.json'})
    output=Path(__file__).with_name('ue_saved_retarget_snapshot.json')
    data=json.loads(output.read_text(encoding='utf-8'))
    data.update(original_saved_asset='/Game/测试/woman/RTG_AutoGenerated.RTG_AutoGenerated',
                original_saved_package_sha256=hashlib.sha256(original).hexdigest(),
                original_package_bytes_preserved=source.read_bytes()==original)
    output.write_text(json.dumps(data,indent=2,ensure_ascii=False),encoding='utf-8')
finally:
    # Delete only the uniquely named temporary asset created by this script.
    unreal.EditorAssetLibrary.delete_asset(saved_path)
    if copy.exists():copy.unlink()
    if directory.exists() and not list(directory.iterdir()):directory.rmdir()

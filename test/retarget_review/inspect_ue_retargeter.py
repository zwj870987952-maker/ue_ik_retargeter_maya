"""Read the live UE 5.8 retargeter without modifying or saving assets."""
import json
import traceback
from pathlib import Path
import unreal

path=globals().get('asset_override','/Game/测试/woman/RTG_AutoGenerated.RTG_AutoGenerated')
asset=unreal.load_asset(path)
controller=unreal.IKRetargeterController.get_controller(asset)
report={'engine_version':unreal.SystemLibrary.get_engine_version(),'asset':path,'ops':[]}

def serialize(value):
    if hasattr(value,'export_text'):return value.export_text()
    if hasattr(value,'get_path_name'):return value.get_path_name()
    return str(value)

for side in [unreal.RetargetSourceOrTarget.SOURCE,unreal.RetargetSourceOrTarget.TARGET]:
    role='Source' if side==unreal.RetargetSourceOrTarget.SOURCE else 'Target'
    rig=controller.get_ik_rig(side)
    report[role]={'rig':serialize(rig),'preview_mesh':serialize(controller.get_preview_mesh(side)),
                  'pose_name':str(controller.get_current_retarget_pose_name(side)),
                  'pose':serialize(controller.get_current_retarget_pose(side))}
target_rig=unreal.IKRigController.get_controller(controller.get_ik_rig(unreal.RetargetSourceOrTarget.TARGET))
chains=[str(c.get_editor_property('chain_name')) for c in target_rig.get_retarget_chains()]
for index in range(controller.get_num_retarget_ops()):
    name=str(controller.get_op_name(index))
    op=controller.get_op_controller(index)
    entry={'index':index,'name':name,'parent':str(controller.get_parent_op_by_name(name)),
           'enabled':controller.get_retarget_op_enabled(index),'controller_type':op.get_class().get_name(),
           'query_methods':[n for n in dir(op) if n.startswith('get_') and any(x in n for x in ['setting','chain','rig'])]}
    for method in ['get_settings','get_op_settings','get_all_chain_settings']:
        if hasattr(op,method):
            try:entry[method]=serialize(getattr(op,method)())
            except Exception as e:entry[method+'_error']=str(e)
    entry['chains']={}
    if hasattr(op,'get_chain_settings'):
        for chain in chains:
            try:entry['chains'][chain]=serialize(op.get_chain_settings(chain))
            except Exception:pass
    entry['chain_mappings']={}
    for chain in chains:
        try:entry['chain_mappings'][chain]=str(controller.get_source_chain(chain,name))
        except Exception:pass
    report['ops'].append(entry)
try:report['raw_ops']=[v.export_text() for v in asset.get_editor_property('retarget_ops')]
except Exception as e:report['raw_ops_error']=str(e)
report['saved_assets']=False
Path(__file__).with_name(globals().get('output_name','ue_retarget_snapshot.json')).write_text(json.dumps(report,indent=2,ensure_ascii=False),encoding='utf-8')
unreal.log('CODEX_RETARGET_REVIEW '+json.dumps([{'index':o['index'],'name':o['name'],'enabled':o['enabled']} for o in report['ops']]))

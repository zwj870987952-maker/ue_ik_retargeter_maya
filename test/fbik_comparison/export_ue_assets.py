"""Run in UE 5.8's Python console to snapshot the two live IK Rig assets.

Reads settings through the supported 5.8 solver controllers. Does not modify
or save Unreal assets. The JSON file is written beside this script.
"""
import json
import traceback
from pathlib import Path
import unreal

OUTPUT = Path(__file__).with_name('ue_asset_snapshot.json')

def fields(value, names):
    result = {}
    for name in names:
        try:
            item = value.get_editor_property(name)
            if isinstance(item, (bool, int, float, str)):
                result[name] = item
            elif isinstance(item, unreal.Vector):
                result[name] = [item.x, item.y, item.z]
            elif hasattr(item, 'get_editor_property') and 'BoneReference' in type(item).__name__:
                result[name] = str(item.get_editor_property('bone_name'))
            else:
                result[name] = str(item)
        except Exception as error:
            result[name] = {'error':str(error)}
    return result

def transform_data(transform):
    p=transform.get_editor_property('translation')
    q=transform.get_editor_property('rotation')
    scale=transform.get_editor_property('scale3d')
    return {'position':[p.x,p.y,p.z], 'rotation_xyzw':[q.x,q.y,q.z,q.w],
            'scale':[scale.x,scale.y,scale.z]}

def snapshot(role):
    path = '/Game/测试/woman/IK_AutoGenerated{0}.IK_AutoGenerated{0}'.format(role)
    rig = unreal.load_asset(path)
    if rig is None:
        raise RuntimeError('Missing asset: ' + path)
    controller = unreal.IKRigController.get_controller(rig)
    chains = controller.get_retarget_chains()
    result = {'asset_path':path, 'mesh':controller.get_skeletal_mesh().get_path_name(),
              'pelvis':str(controller.get_retarget_root()), 'chains':[], 'solvers':[]}
    try:
        result['solver_stack_export_text']=[v.export_text() for v in rig.get_editor_property('solver_stack')]
    except Exception as error:
        result['solver_stack_export_error']=str(error)
    bone_names = set()
    for chain in chains:
        entry = fields(chain, ['chain_name','start_bone','end_bone','ik_goal_name'])
        result['chains'].append(entry)
        bone_names.update([entry['start_bone'],entry['end_bone']])
    # Include internal spine, hinge and template bones that are not chain endpoints.
    for name in ['CC_Base_Hip','CC_Base_Pelvis','CC_Base_Waist','CC_Base_Spine01','CC_Base_Spine02',
                 'CC_Base_L_Upperarm','CC_Base_R_Upperarm','CC_Base_L_Forearm','CC_Base_R_Forearm',
                 'CC_Base_L_Thigh','CC_Base_R_Thigh','CC_Base_L_Calf','CC_Base_R_Calf',
                 'Hips','Spine','Spine1','Spine2','LeftForeArm','RightForeArm','LeftLeg','RightLeg']:
        bone_names.add(name)
    result['api_methods'] = [n for n in dir(controller) if 'bone' in n or 'goal' in n]
    try:
        bone_names.update(str(n) for n in controller.get_all_bone_names())
    except AttributeError:
        pass
    for index in range(controller.get_num_solvers()):
        solver = controller.get_solver_controller(index)
        entry = {'index':index, 'enabled':controller.get_solver_enabled(index),
                 'controller_type':solver.get_class().get_name(), 'root':str(controller.get_start_bone(index))}
        settings = solver.get_solver_settings()
        entry['settings'] = fields(settings, ['root_bone','iterations','sub_iterations','mass_multiplier',
            'allow_stretch','root_behavior','global_pull_chain_alpha','max_angle','over_relaxation'])
        entry['settings_text'] = settings.export_text()
        entry['goals'] = []
        for chain in chains:
            name = str(chain.get_editor_property('ik_goal_name'))
            if name == 'None':
                continue
            goal = controller.get_goal(name)
            goal_entry = {'name':name, 'bone':str(controller.get_bone_for_goal(name)),
                          'solver_settings':fields(solver.get_goal_settings(name),
                            ['goal','bone_name','chain_depth','strength_alpha','pull_chain_alpha','pin_rotation'])}
            if goal:
                goal_entry['goal_settings'] = fields(goal,['position_alpha','rotation_alpha','preview_mode'])
                goal_entry['current_transform'] = transform_data(goal.get_editor_property('current_transform'))
                goal_entry['initial_transform'] = transform_data(goal.get_editor_property('initial_transform'))
            entry['goals'].append(goal_entry)
        entry['bones'] = {}
        entry['excluded_bones'] = []
        for bone in sorted(bone_names):
            try:
                if controller.get_bone_excluded(bone):
                    entry['excluded_bones'].append(bone)
                setting = solver.get_bone_settings(bone)
                # The controller returns a default struct even for bones without
                # an explicit setting. Store only non-default effective settings.
                effective=fields(setting,['bone','rotation_stiffness','position_stiffness',
                    'x','y','z','min_x','max_x','min_y','max_y','min_z','max_z','use_preferred_angles','preferred_angles'])
                if not (effective['rotation_stiffness'] or effective['position_stiffness'] or
                        effective['use_preferred_angles'] or any('FREE' not in effective[a] for a in ['x','y','z'])):
                    continue
                entry['bones'][bone] = effective
            except Exception:
                pass
        result['solvers'].append(entry)
    return result

data = {'engine_version':unreal.SystemLibrary.get_engine_version(), 'assets':{}}
for role in ['Source','Target']:
    try:
        data['assets'][role] = snapshot(role)
    except Exception:
        data['assets'][role] = {'error':traceback.format_exc()}
OUTPUT.write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
unreal.log('CODEX_FBIK_SNAPSHOT ' + str(OUTPUT))

"""Read every goal, including goals not assigned to a retarget chain."""
import json
from pathlib import Path
import unreal

result={'engine_version':unreal.SystemLibrary.get_engine_version(),'assets':{}}
for role in ['Source','Target']:
    path='/Game/测试/woman/IK_AutoGenerated{0}.IK_AutoGenerated{0}'.format(role)
    rig=unreal.load_asset(path)
    controller=unreal.IKRigController.get_controller(rig)
    goals=[{'name':str(g.get_editor_property('goal_name')),
            'bone':str(g.get_editor_property('bone_name'))} for g in controller.get_all_goals()]
    solvers=[]
    for index in range(controller.get_num_solvers()):
        settings=controller.get_solver_controller(index).get_solver_settings()
        solvers.append({'root_bone':str(controller.get_start_bone(index)),
                        'root_behavior':str(settings.get_editor_property('root_behavior'))})
    result['assets'][role]={'path':path,'retarget_root':str(controller.get_retarget_root()),
                            'all_goals':goals,'solvers':solvers}
Path(__file__).with_name('ue_pelvis_goal_check.json').write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding='utf-8')
unreal.log('CODEX_PELVIS_GOAL_CHECK '+json.dumps(result,ensure_ascii=False))

    @classmethod
    def resolve_source_and_target_from_selection(cls, source_root=None, target_root=None):
        """
        Resolves Source A and Target B full DAG root joint paths from user selection
        (or scene if not passed), with 100% duplicate-name safety (`cmds.ls(sl=True, long=True)`).
        """
        if source_root and target_root:
            src_dag = resolve_skeleton_root_joint(source_root)
            tgt_dag = resolve_skeleton_root_joint(target_root)
            if src_dag and tgt_dag:
                return src_dag, tgt_dag

        sel = cmds.ls(sl=True, long=True) or []
        resolved_roots = []
        for item in sel:
            r_dag = resolve_skeleton_root_joint(item)
            if r_dag and r_dag not in resolved_roots:
                resolved_roots.append(r_dag)

        if len(resolved_roots) >= 2:
            return resolved_roots[0], resolved_roots[1]

        # Fallback: find top-level root joints in scene (excluding our own generated asset container)
        all_joints = cmds.ls(type="joint", long=True) or []
        top_roots = []
        for j in all_joints:
            if "|UE58_RetargetAssets_Grp|" in j:
                continue
            parent_j = cmds.listRelatives(j, parent=True, type="joint", fullPath=True)
            if not parent_j and j not in top_roots:
                top_roots.append(j)

        if len(top_roots) >= 2:
            return top_roots[0], top_roots[1]

        raise RuntimeError(
            "Please select Skeleton A (Source) and Skeleton B (Target) in the Maya scene "
            "(you can select their root joints, any bone on A and B, their character groups, or meshes)."
        )

    @classmethod
    def generate_assets_from_selection(
        cls,
        source_root=None,
        target_root=None,
        output_dir=None,
        build_in_scene=True,
        apply_aligned_pose=True,
    ):
        """
        One-call verification entrypoint:
        Takes the user's current selection (Skeleton A and Skeleton B) in Maya,
        characterizes both skeletons, auto-aligns Target B's Retarget Pose to Source A,
        and directly generates `IK_AutoGeneratedSource`, `IK_AutoGeneratedTarget`, and
        `RTG_AutoGenerated` inside the current Maya scene + exports the 3 JSON files.
        """
        src_dag, tgt_dag = cls.resolve_source_and_target_from_selection(source_root, target_root)
        processor = cls(src_dag, tgt_dag)
        return processor.generate_three_assets(
            output_dir=output_dir,
            build_in_scene=build_in_scene,
            apply_aligned_pose=apply_aligned_pose,
        )

    @classmethod
    def one_click_retarget(cls, source_root=None, target_root=None, start_frame=None, end_frame=None):
        """
        All-in-one entrypoint matching UE 5.8's auto-retarget behavior.
        """
        src_dag, tgt_dag = cls.resolve_source_and_target_from_selection(source_root, target_root)

        if start_frame is None:
            start_frame = int(cmds.playbackOptions(q=True, minTime=True))
        if end_frame is None:
            end_frame = int(cmds.playbackOptions(q=True, maxTime=True))

        print("[UE5.8 Retargeter] Initializing processor for: {} -> {}".format(src_dag, tgt_dag))
        processor = cls(src_dag, tgt_dag)
        processor.generate_three_assets(build_in_scene=True, apply_aligned_pose=True)

        print("[UE5.8 Retargeter] Baking animation from frame {} to {}...".format(start_frame, end_frame))
        processor.bake_animation(start_frame, end_frame)

        print("[UE5.8 Retargeter] One-click retarget completed successfully!")
        return processor


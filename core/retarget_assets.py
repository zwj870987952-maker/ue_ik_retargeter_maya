def _sanitize_maya_name(name):
    """Converts any string into a valid Maya node name token."""
    clean = re.sub(r"[^A-Za-z0-9_]", "_", str(name or "Skeleton"))
    clean = re.sub(r"_+", "_", clean).strip("_")
    if not clean or clean[0].isdigit():
        clean = "Skel_" + clean
    return clean


def derive_unique_skeleton_tags(source_skeleton, target_skeleton):
    """
    Derives human-readable, guaranteed-unique tags for Source A and Target B,
    even if both skeletons have the exact same joint names.
    """
    def _extract_tag(skel):
        dag = skel.root_joint
        parts = [p for p in dag.split("|") if p]
        if len(parts) >= 2:
            top_grp = parts[0].split(":")[-1]
            root_short = parts[-1].split(":")[-1]
            if top_grp.lower() != root_short.lower():
                return _sanitize_maya_name("{}_{}".format(top_grp, root_short))
        short_with_ns = parts[-1] if parts else "Skeleton"
        if ":" in short_with_ns:
            return _sanitize_maya_name(short_with_ns.replace(":", "_"))
        return _sanitize_maya_name(short_with_ns)

    src_tag = _extract_tag(source_skeleton)
    tgt_tag = _extract_tag(target_skeleton)

    if src_tag == tgt_tag:
        src_tag = src_tag + "_SrcA"
        tgt_tag = tgt_tag + "_TgtB"

    return src_tag, tgt_tag


def _vec_to_list(v):
    return [round(float(v.x), 6), round(float(v.y), 6), round(float(v.z), 6)]


def _quat_to_list(q):
    return [round(float(q.x), 6), round(float(q.y), 6), round(float(q.z), 6), round(float(q.w), 6)]


def _quat_to_deg_list(q):
    deg = quat_to_euler_deg(q)
    return [round(float(deg[0]), 3), round(float(deg[1]), 3), round(float(deg[2]), 3)]


def _add_str_attr(node_dag, attr_name, value):
    if not cmds.attributeQuery(attr_name, node=node_dag, exists=True):
        cmds.addAttr(node_dag, longName=attr_name, dataType="string")
    cmds.setAttr("{}.{}".format(node_dag, attr_name), str(value), type="string")


def _add_float_attr(node_dag, attr_name, value, keyable=False):
    if not cmds.attributeQuery(attr_name, node=node_dag, exists=True):
        cmds.addAttr(node_dag, longName=attr_name, attributeType="double", keyable=keyable)
    cmds.setAttr("{}.{}".format(node_dag, attr_name), float(value))
    if not keyable:
        cmds.setAttr("{}.{}".format(node_dag, attr_name), channelBox=True)


def _add_int_attr(node_dag, attr_name, value):
    if not cmds.attributeQuery(attr_name, node=node_dag, exists=True):
        cmds.addAttr(node_dag, longName=attr_name, attributeType="long", keyable=False)
    cmds.setAttr("{}.{}".format(node_dag, attr_name), int(value))
    cmds.setAttr("{}.{}".format(node_dag, attr_name), channelBox=True)


def _add_bool_attr(node_dag, attr_name, value):
    if not cmds.attributeQuery(attr_name, node=node_dag, exists=True):
        cmds.addAttr(node_dag, longName=attr_name, attributeType="bool", keyable=False)
    cmds.setAttr("{}.{}".format(node_dag, attr_name), bool(value))
    cmds.setAttr("{}.{}".format(node_dag, attr_name), channelBox=True)


def _set_outliner_color(node_dag, rgb):
    try:
        cmds.setAttr(node_dag + ".useOutlinerColor", True)
        cmds.setAttr(node_dag + ".outlinerColor", rgb[0], rgb[1], rgb[2], type="double3")
    except Exception:
        pass


def _set_wire_color(node_dag, rgb, line_width=2.0):
    try:
        shapes = cmds.listRelatives(node_dag, shapes=True, fullPath=True) or [node_dag]
        for s in shapes:
            cmds.setAttr(s + ".overrideEnabled", 1)
            cmds.setAttr(s + ".overrideRGBColors", 1)
            cmds.setAttr(s + ".overrideColorRGB", rgb[0], rgb[1], rgb[2], type="double3")
            if cmds.attributeQuery("lineWidth", node=s, exists=True):
                cmds.setAttr(s + ".lineWidth", float(line_width))
    except Exception:
        pass


class IKRigAsset(object):
    """
    Python representation of UE 5.8's UIKRigDefinition asset
    (IK_AutoGeneratedSource or IK_AutoGeneratedTarget).
    """

    def __init__(self, asset_name, role, skeleton, char_profile):
        self.asset_name = asset_name
        self.role = role
        self.skeleton = skeleton
        self.char_profile = char_profile

    def to_dict(self):
        skel = self.skeleton
        prof = self.char_profile

        skeleton_bones = []
        for idx, dag in enumerate(skel.joint_names):
            p_idx = skel.parent_indices[idx]
            p_dag = skel.joint_names[p_idx] if p_idx >= 0 else ""
            p_clean = skel.get_clean_name(p_dag) if p_dag else ""
            skeleton_bones.append({
                "index": idx,
                "clean_name": skel.get_clean_name(dag),
                "short_name": skel.get_short_name(dag),
                "dag_path": dag,
                "parent_index": p_idx,
                "parent_clean_name": p_clean,
                "parent_dag_path": p_dag,
                "ref_world_pos": _vec_to_list(skel.rest_world_pos[dag]),
                "ref_world_rot": _quat_to_list(skel.rest_world_rot[dag]),
                "ref_local_pos": _vec_to_list(skel.rest_local_pos[dag]),
                "ref_local_rot": _quat_to_list(skel.rest_local_rot[dag]),
            })

        retarget_chains = []
        for c in prof["chains"]:
            b_chain = prof["bone_chains"].get(c["chain_name"])
            retarget_chains.append({
                "chain_name": c["chain_name"],
                "start_bone": c["start_bone"],
                "end_bone": c["end_bone"],
                "start_bone_dag": c["start_bone_dag"],
                "end_bone_dag": c["end_bone_dag"],
                "ik_goal_name": c["ik_goal_name"],
                "bones": b_chain.clean_bones if b_chain else [],
                "bone_dags": b_chain.bones if b_chain else [],
                "params": [round(p, 4) for p in b_chain.params] if b_chain else [],
                "total_length": round(b_chain.total_initial_length, 4) if b_chain else 0.0,
            })

        ik_goals = []
        for g in prof["ik_goals"]:
            b_dag = g["bone_dag"]
            pos = skel.rest_world_pos.get(b_dag, om.MVector(0, 0, 0))
            rot = skel.rest_world_rot.get(b_dag, om.MQuaternion.kIdentity)
            ik_goals.append({
                "goal_name": g["goal_name"],
                "bone_name": g["bone_name"],
                "bone_dag": b_dag,
                "chain_name": g["chain_name"],
                "initial_world_pos": _vec_to_list(pos),
                "initial_world_rot": _quat_to_list(rot),
                "position_alpha": g.get("position_alpha", 1.0),
                "rotation_alpha": g.get("rotation_alpha", 1.0),
                "position_space": g.get("position_space", "Additive"),
                "rotation_space": g.get("rotation_space", "Additive"),
            })

        return {
            "asset_type": "UIKRigDefinition",
            "ue_version": "5.8",
            "asset_name": self.asset_name,
            "role": self.role,
            "created_at": datetime.datetime.now().isoformat(),
            "template_matched": prof["template_name"],
            "template_score": round(prof["match_score"], 4),
            "skeleton": {
                "root_joint_dag": skel.root_joint,
                "root_bone_clean": prof["root_bone"],
                "pelvis_bone_clean": prof["pelvis_bone"],
                "pelvis_bone_dag": prof["pelvis_bone_dag"],
                "common_prefix": skel.common_prefix,
                "bone_count": len(skel.joint_names),
                "bones": skeleton_bones,
            },
            "retarget_definition": {
                "root_bone": prof["pelvis_bone"],
                "root_bone_dag": prof["pelvis_bone_dag"],
                "bone_chains": retarget_chains,
            },
            "goals": ik_goals,
            "solvers": [
                {
                    "solver_type": "FIKRigFullBodyIKSolver",
                    "root_bone": prof["pelvis_bone"],
                    "root_bone_dag": prof["pelvis_bone_dag"],
                    "root_behavior": "PinToInput",
                    "allow_stretch": False,
                    "bone_settings": prof["fbik_bone_settings"],
                }
            ],
            "bones_to_exclude_from_auto_pose": prof["bones_to_exclude_from_auto_pose"],
            "bones_to_pin": prof["bones_to_pin"],
        }


class IKRetargeterAsset(object):
    """
    Python representation of UE 5.8's UIKRetargeter asset (RTG_AutoGenerated).
    """

    def __init__(self, asset_name, source_ikrig, target_ikrig, processor):
        self.asset_name = asset_name
        self.source_ikrig = source_ikrig
        self.target_ikrig = target_ikrig
        self.processor = processor

    def to_dict(self):
        proc = self.processor
        src_skel = proc.source_skeleton
        tgt_skel = proc.target_skeleton
        tgt_pose = proc.target_pose_mgr

        world_rotation_deltas = {}
        local_rotation_offsets = {}
        for j_dag, w_quat in tgt_pose.delta_rotations.items():
            clean_name = tgt_skel.get_clean_name(j_dag)
            world_rotation_deltas[j_dag] = {
                "clean_name": clean_name,
                "quat": _quat_to_list(w_quat),
                "euler_deg": _quat_to_deg_list(w_quat),
            }
        for j_dag, l_quat in tgt_pose.local_delta_rotations.items():
            clean_name = tgt_skel.get_clean_name(j_dag)
            local_rotation_offsets[j_dag] = {
                "clean_name": clean_name,
                "quat": _quat_to_list(l_quat),
                "euler_deg": _quat_to_deg_list(l_quat),
            }

        aligned_target_transforms = {}
        for j_dag in tgt_skel.joint_names:
            aligned_target_transforms[j_dag] = {
                "clean_name": tgt_skel.get_clean_name(j_dag),
                "world_pos": _vec_to_list(tgt_pose.get_aligned_rest_position(j_dag)),
                "world_rot": _quat_to_list(tgt_pose.get_aligned_rest_rotation(j_dag)),
            }

        chain_mappings = []
        ik_chain_names = []
        for m in proc.chain_mappings:
            if m.enable_ik:
                ik_chain_names.append(m.name)
            chain_mappings.append({
                "target_chain": m.name,
                "source_chain": m.name,
                "source_start_bone": src_skel.get_clean_name(m.source_chain.start_bone),
                "source_end_bone": src_skel.get_clean_name(m.source_chain.end_bone),
                "source_start_dag": m.source_chain.start_bone,
                "source_end_dag": m.source_chain.end_bone,
                "target_start_bone": tgt_skel.get_clean_name(m.target_chain.start_bone),
                "target_end_bone": tgt_skel.get_clean_name(m.target_chain.end_bone),
                "target_start_dag": m.target_chain.start_bone,
                "target_end_dag": m.target_chain.end_bone,
                "enable_fk": m.enable_fk,
                "enable_ik": m.enable_ik,
                "ik_goal_name": m.ik_goal_name,
                "rotation_mode": m.rotation_mode,
                "rotation_alpha": m.rotation_alpha,
                "translation_mode": m.translation_mode,
                "translation_alpha": m.translation_alpha,
            })

        pelvis_solv = proc.pelvis_solver
        retarget_ops = [
            {
                "op_index": 0,
                "op_type": "FIKRetargetPelvisMotionOp",
                "enabled": True,
                "settings": {
                    "source_pelvis_bone": src_skel.get_clean_name(proc.source_pelvis),
                    "source_pelvis_dag": proc.source_pelvis,
                    "target_pelvis_bone": tgt_skel.get_clean_name(proc.target_pelvis),
                    "target_pelvis_dag": proc.target_pelvis,
                    "height_ratio": round(pelvis_solv.height_ratio if pelvis_solv else 1.0, 4),
                    "scale_horizontal": pelvis_solv.scale_horizontal if pelvis_solv else 1.0,
                    "scale_vertical": pelvis_solv.scale_vertical if pelvis_solv else 1.0,
                    "blend_to_absolute": pelvis_solv.blend_to_absolute if pelvis_solv else 0.0,
                    "floor_constraint_weight": pelvis_solv.floor_constraint_weight if pelvis_solv else 1.0,
                    "affect_ik_horizontal": getattr(pelvis_solv, "affect_ik_horizontal", 1.0),
                    "affect_ik_vertical": getattr(pelvis_solv, "affect_ik_vertical", 1.0),
                },
            },
            {
                "op_index": 1,
                "op_type": "FIKRetargetFKChainsOp",
                "enabled": True,
                "settings": {
                    "ik_rig_asset": self.target_ikrig.asset_name,
                    "chain_count": len(chain_mappings),
                    "chains_to_retarget": [m["target_chain"] for m in chain_mappings],
                },
            },
            {
                "op_index": 2,
                "op_type": "FIKRetargetIKChainsOp",
                "enabled": bool(getattr(proc, "enable_ik_pass", True)),
                "settings": {
                    "ik_chains": ik_chain_names,
                    "drive_with_source_ik": True,
                },
            },
            {
                "op_index": 3,
                "op_type": "FIKRetargetRunIKRigOp",
                "enabled": bool(getattr(proc, "enable_ik_pass", True)),
                "settings": {
                    "ik_rig_asset": self.target_ikrig.asset_name,
                    "excluded_goals": [],
                },
            },
            {
                "op_index": 4,
                "op_type": "FIKRetargetAlignPoleVectorOp",
                "enabled": bool(getattr(proc, "enable_pole_vector_op", True)),
                "settings": {
                    "ik_rig_asset": self.target_ikrig.asset_name,
                    "chains_to_align": ik_chain_names,
                },
            },
            {
                "op_index": 5,
                "op_type": "FIKRetargetPinBoneOp",
                "enabled": bool(self.target_ikrig.char_profile.get("bones_to_pin")),
                "settings": {
                    "bones_to_pin": self.target_ikrig.char_profile.get("bones_to_pin", []),
                },
            },
            {
                "op_index": 6,
                "op_type": "FIKRetargetRootMotionOp",
                "enabled": bool(
                    self.source_ikrig.char_profile.get("root_bone") and
                    self.target_ikrig.char_profile.get("root_bone")
                ),
                "settings": {
                    "source_root_bone": self.source_ikrig.char_profile.get("root_bone", ""),
                    "target_root_bone": self.target_ikrig.char_profile.get("root_bone", ""),
                },
            },
        ]

        return {
            "asset_type": "UIKRetargeter",
            "ue_version": "5.8",
            "asset_name": self.asset_name,
            "created_at": datetime.datetime.now().isoformat(),
            "source_ik_rig_asset": self.source_ikrig.asset_name,
            "target_ik_rig_asset": self.target_ikrig.asset_name,
            "source_ik_rig_file": self.source_ikrig.asset_name + ".ikrig.json",
            "target_ik_rig_file": self.target_ikrig.asset_name + ".ikrig.json",
            "current_source_retarget_pose": "DefaultRetargetPose",
            "current_target_retarget_pose": "DefaultRetargetPose",
            "source_retarget_poses": {
                "DefaultRetargetPose": {
                    "root_translation_offset": [0.0, 0.0, 0.0],
                    "bone_rotation_offsets": {},
                }
            },
            "target_retarget_poses": {
                "DefaultRetargetPose": {
                    "root_translation_offset": _vec_to_list(tgt_pose.root_translation_offset),
                    "bone_rotation_offsets_local": local_rotation_offsets,
                    "bone_rotation_deltas_world": world_rotation_deltas,
                    "aligned_world_transforms": aligned_target_transforms,
                }
            },
            "bones_to_exclude_from_auto_pose": getattr(proc, "bones_to_exclude_from_auto_pose", []),
            "chain_mappings": chain_mappings,
            "retarget_ops": retarget_ops,
        }


class MayaSceneAssetBuilder(object):
    """
    Builds and visualizes the 3 UE 5.8 Retarget Assets directly inside the current Maya scene:
    1. Live-connects every CV of every BoneChain curve to the skeleton's joints via `pointMatrixMult`.
    2. Wires up real-time Full-Body IK (`FullBodyIKSolver`) driven by the IK Effector Goal locators.
    """

    CONTAINER_GRP = "UE58_RetargetAssets_Grp"

    @classmethod
    def build_in_scene(
        cls,
        processor,
        src_ikrig_asset,
        tgt_ikrig_asset,
        rtg_asset,
        src_json_path="",
        tgt_json_path="",
        rtg_json_path="",
        apply_aligned_pose_to_target=True,
    ):
        src_tag, tgt_tag = derive_unique_skeleton_tags(
            processor.source_skeleton, processor.target_skeleton
        )

        # Clear any previous live FBIK callbacks for these skeletons before rebuilding
        clear_fbik_callbacks("Src_" + src_tag)
        clear_fbik_callbacks("Tgt_" + tgt_tag)

        # Reset Source A to its pristine bind pose and Target B to its aligned Retarget Pose
        for idx, j in enumerate(processor.source_skeleton.joint_names):
            if idx == 0:
                set_world_transform(j, processor.source_skeleton.rest_world_pos[j], processor.source_skeleton.rest_world_rot[j])
            else:
                set_world_transform(j, quat=processor.source_skeleton.rest_world_rot[j])

        if apply_aligned_pose_to_target:
            processor.target_pose_mgr.apply_aligned_pose_to_scene()

        top_grp_dag = "|" + cls.CONTAINER_GRP
        if not cmds.objExists(top_grp_dag):
            created = cmds.group(empty=True, name=cls.CONTAINER_GRP, world=True)
            top_grp_dag = cmds.ls(created, long=True)[0]
            _set_outliner_color(top_grp_dag, (0.35, 0.75, 1.0))
            _add_str_attr(top_grp_dag, "description", "UE 5.8 Standard 3-Asset Retargeting Container")

        # 1. Build IK_AutoGeneratedSource node hierarchy + Live Chain Binding + Live FBIK
        src_node_dag, src_fbik = cls._build_ikrig_scene_node(
            parent_dag=top_grp_dag,
            ikrig_asset=src_ikrig_asset,
            tag="Src_" + src_tag,
            pose_mgr=None,
            json_path=src_json_path,
            wire_rgb=(0.15, 0.85, 1.0),
            outliner_rgb=(0.25, 0.85, 1.0),
        )
        processor.source_fbik_solver = src_fbik

        # 2. Build IK_AutoGeneratedTarget node hierarchy + Live Chain Binding + Live FBIK
        tgt_node_dag, tgt_fbik = cls._build_ikrig_scene_node(
            parent_dag=top_grp_dag,
            ikrig_asset=tgt_ikrig_asset,
            tag="Tgt_" + tgt_tag,
            pose_mgr=processor.target_pose_mgr if apply_aligned_pose_to_target else None,
            json_path=tgt_json_path,
            wire_rgb=(0.2, 1.0, 0.45),
            outliner_rgb=(0.3, 1.0, 0.5),
        )
        processor.target_fbik_solver = tgt_fbik

        # 3. Build RTG_AutoGenerated node hierarchy
        rtg_node_dag = cls._build_rtg_scene_node(
            parent_dag=top_grp_dag,
            rtg_asset=rtg_asset,
            pair_tag="{}_to_{}".format(src_tag, tgt_tag),
            json_path=rtg_json_path,
            outliner_rgb=(1.0, 0.75, 0.25),
        )

        return {
            "container_group": top_grp_dag,
            "IK_AutoGeneratedSource": src_node_dag,
            "IK_AutoGeneratedTarget": tgt_node_dag,
            "RTG_AutoGenerated": rtg_node_dag,
        }

    @classmethod
    def _recreate_child_group(cls, parent_dag, child_name):
        existing_dag = "{}|{}".format(parent_dag, child_name)
        if cmds.objExists(existing_dag):
            cmds.delete(existing_dag)
        node = cmds.createNode("transform", name=child_name, parent=parent_dag, skipSelect=True)
        return cmds.ls(node, long=True)[0]

    @classmethod
    def _resolve_chain_curve_joints(cls, skel, b_chain):
        """
        Returns a list of >= 2 joint DAG paths for drawing and live-binding a BoneChain curve.
        For single-bone chains (e.g. LeftClavicle, Neck, Head, LeftFoot), connects the bone
        with its child joint or parent joint so every chain has a visible live-bound 3D curve!
        """
        if len(b_chain.bones) >= 2:
            return list(b_chain.bones)

        single_dag = b_chain.bones[0]
        # Prefer child joint if one exists (e.g. LeftShoulder -> LeftArm, Neck -> Head)
        children = cmds.listRelatives(single_dag, children=True, type="joint", fullPath=True) or []
        if children:
            return [single_dag, children[0]]

        # Otherwise connect from parent joint to single_dag (e.g. LeftFoot -> LeftToeBase, Neck -> Head)
        parent_dag = skel.get_parent_joint(single_dag)
        if parent_dag:
            return [parent_dag, single_dag]

        return [single_dag]

    @classmethod
    def _build_ikrig_scene_node(cls, parent_dag, ikrig_asset, tag, pose_mgr, json_path, wire_rgb, outliner_rgb):
        """
        Builds an in-scene representation of UIKRigDefinition:
        - Live-connected 3D BoneChain curves (bound to joints via `pointMatrixMult` + `.connectedBones`)
        - Interactive IK Effector Goal locators (`LeftHandIK`, `RightHandIK`, `LeftFootIK`, `RightFootIK`, `Pelvis_RootGoal`)
        - Live Full-Body IK solver (`FullBodyIKSolver`)
        """
        asset_node_dag = cls._recreate_child_group(parent_dag, ikrig_asset.asset_name)
        _set_outliner_color(asset_node_dag, outliner_rgb)

        skel = ikrig_asset.skeleton
        prof = ikrig_asset.char_profile

        _add_str_attr(asset_node_dag, "ueAssetType", "UIKRigDefinition (UE 5.8)")
        _add_str_attr(asset_node_dag, "retargetRole", ikrig_asset.role)
        _add_str_attr(asset_node_dag, "templateMatched", prof["template_name"])
        _add_float_attr(asset_node_dag, "templateScore", round(prof["match_score"], 3))
        _add_str_attr(asset_node_dag, "skeletonRootDAG", skel.root_joint)
        _add_str_attr(asset_node_dag, "pelvisBone", prof["pelvis_bone"])
        _add_str_attr(asset_node_dag, "pelvisBoneDAG", prof["pelvis_bone_dag"])
        _add_int_attr(asset_node_dag, "totalBoneCount", len(skel.joint_names))
        _add_int_attr(asset_node_dag, "retargetChainCount", len(prof["chains"]))
        _add_int_attr(asset_node_dag, "ikGoalCount", len(prof["ik_goals"]))
        _add_str_attr(
            asset_node_dag,
            "bonesExcludedFromAutoPose",
            ", ".join(prof.get("bones_to_exclude_from_auto_pose", []))
        )
        if json_path:
            _add_str_attr(asset_node_dag, "exportedJsonFile", json_path)

        # ----------------------------------------------------------------------
        # 1. Sub-group: RetargetChains (Live-connected to Skeleton Joints via DG)
        # ----------------------------------------------------------------------
        chains_grp = cls._recreate_child_group(
            asset_node_dag, "RetargetChains_{}".format(tag)
        )
        _add_int_attr(chains_grp, "chainCount", len(prof["chains"]))

        for c_info in prof["chains"]:
            cname = c_info["chain_name"]
            b_chain = prof["bone_chains"].get(cname)
            if not b_chain or not b_chain.bones:
                continue

            node_name = "Chain_{}_{}".format(tag, _sanitize_maya_name(cname))
            curve_joints = cls._resolve_chain_curve_joints(skel, b_chain)

            pts = []
            for j_dag in curve_joints:
                p = pose_mgr.get_aligned_rest_position(j_dag) if pose_mgr else skel.rest_world_pos[j_dag]
                pts.append((p.x, p.y, p.z))

            if len(pts) >= 2:
                crv = cmds.curve(degree=1, point=pts, name=node_name)
                crv_dag = cmds.ls(crv, long=True)[0]
                crv_dag = cmds.ls(cmds.parent(crv_dag, chains_grp)[0], long=True)[0]
                # Set inheritsTransform=False so world-space controlPoints place CVs directly on joints
                cmds.setAttr(crv_dag + ".inheritsTransform", False)
                cmds.xform(crv_dag, ws=True, t=(0, 0, 0), ro=(0, 0, 0))
                _set_wire_color(crv_dag, wire_rgb, line_width=2.5)

                # Live-bind each CV of the curve to the joint's worldMatrix[0] via pointMatrixMult
                crv_shapes = cmds.listRelatives(crv_dag, shapes=True, fullPath=True) or []
                if crv_shapes:
                    crv_shape = crv_shapes[0]
                    for cv_idx, j_dag in enumerate(curve_joints):
                        pmm_name = "PMM_{}_{}_{}".format(tag, _sanitize_maya_name(cname), cv_idx)
                        if cmds.objExists(pmm_name):
                            cmds.delete(pmm_name)
                        pmm = cmds.createNode("pointMatrixMult", name=pmm_name, skipSelect=True)
                        cmds.setAttr(pmm + ".inPoint", 0.0, 0.0, 0.0, type="double3")
                        cmds.setAttr(pmm + ".vectorMultiply", False)
                        cmds.connectAttr(j_dag + ".worldMatrix[0]", pmm + ".inMatrix", force=True)
                        cmds.connectAttr(
                            pmm + ".output",
                            "{}.controlPoints[{}]".format(crv_shape, cv_idx),
                            force=True,
                        )
                chain_node_dag = crv_dag
            else:
                chain_node_dag = cls._recreate_child_group(chains_grp, node_name)
                cmds.pointConstraint(curve_joints[0], chain_node_dag, maintainOffset=False)

            # Also connect explicit message attributes from every chain joint to chain_node_dag
            if not cmds.attributeQuery("connectedBones", node=chain_node_dag, exists=True):
                cmds.addAttr(chain_node_dag, longName="connectedBones", attributeType="message", multi=True)
            for b_idx, b_dag in enumerate(b_chain.bones):
                try:
                    cmds.connectAttr(
                        b_dag + ".message",
                        "{}.connectedBones[{}]".format(chain_node_dag, b_idx),
                        force=True,
                    )
                except Exception:
                    pass

            _add_str_attr(chain_node_dag, "chainName", cname)
            _add_str_attr(chain_node_dag, "startBone", c_info["start_bone"])
            _add_str_attr(chain_node_dag, "endBone", c_info["end_bone"])
            _add_str_attr(chain_node_dag, "startBoneDAG", c_info["start_bone_dag"])
            _add_str_attr(chain_node_dag, "endBoneDAG", c_info["end_bone_dag"])
            _add_str_attr(chain_node_dag, "ikGoalName", c_info["ik_goal_name"] or "None")
            _add_int_attr(chain_node_dag, "boneCount", len(b_chain.bones))
            _add_float_attr(chain_node_dag, "chainLength", round(b_chain.total_initial_length, 3))
            _add_str_attr(chain_node_dag, "boneList", " -> ".join(b_chain.clean_bones))
            _add_str_attr(
                chain_node_dag,
                "normalizedParams",
                ", ".join("{:.2f}".format(p) for p in b_chain.params)
            )

        # ----------------------------------------------------------------------
        # 2. Sub-group: IKEffectorGoals + Live FullBodyIKSolver
        # ----------------------------------------------------------------------
        goals_grp = cls._recreate_child_group(
            asset_node_dag, "IKEffectorGoals_{}".format(tag)
        )
        _add_int_attr(goals_grp, "goalCount", len(prof["ik_goals"]))

        fbik_solver = FullBodyIKSolver(
            solver_key=tag,
            skeleton=skel,
            char_profile=prof,
            pose_mgr=pose_mgr,
        )

        pelvis_dag = prof["pelvis_bone_dag"]
        pelvis_pos = pose_mgr.get_aligned_rest_position(pelvis_dag) if pose_mgr else skel.rest_world_pos.get(pelvis_dag, om.MVector(0, 90, 0))
        pelvis_rot = pose_mgr.get_aligned_rest_rotation(pelvis_dag) if pose_mgr else skel.rest_world_rot.get(pelvis_dag, om.MQuaternion.kIdentity)
        loc_scale = max(3.5, abs(pelvis_pos.y) * 0.075)

        # Create Pelvis Root FBIK Control Locator (allows crouching / shifting hips with hands & feet pinned!)
        pelvis_loc_name = "Goal_{}_PelvisRoot".format(tag)
        pelvis_loc = cmds.spaceLocator(name=pelvis_loc_name)[0]
        pelvis_loc_dag = cmds.ls(pelvis_loc, long=True)[0]
        pelvis_loc_dag = cmds.ls(cmds.parent(pelvis_loc_dag, goals_grp)[0], long=True)[0]
        set_world_transform(pelvis_loc_dag, pelvis_pos, pelvis_rot)
        for s in cmds.listRelatives(pelvis_loc_dag, shapes=True, fullPath=True) or []:
            cmds.setAttr(s + ".localScaleX", loc_scale * 1.35)
            cmds.setAttr(s + ".localScaleY", loc_scale * 1.35)
            cmds.setAttr(s + ".localScaleZ", loc_scale * 1.35)
        _set_wire_color(pelvis_loc_dag, (1.0, 0.45, 0.1), line_width=2.5)
        _set_outliner_color(pelvis_loc_dag, (1.0, 0.55, 0.2))
        _add_str_attr(pelvis_loc_dag, "goalName", "PelvisRoot")
        _add_str_attr(pelvis_loc_dag, "boneName", prof["pelvis_bone"])
        _add_str_attr(pelvis_loc_dag, "boneDAG", pelvis_dag)
        if not cmds.attributeQuery("drivenBone", node=pelvis_loc_dag, exists=True):
            cmds.addAttr(pelvis_loc_dag, longName="drivenBone", attributeType="message")
        try:
            cmds.connectAttr(pelvis_dag + ".message", pelvis_loc_dag + ".drivenBone", force=True)
        except Exception:
            pass
        fbik_solver.register_pelvis_locator(pelvis_loc_dag)

        # Create the 4 Limb IK Effector Goal Locators (LeftHandIK, RightHandIK, LeftFootIK, RightFootIK)
        for g_info in prof["ik_goals"]:
            g_name = g_info["goal_name"]
            b_dag = g_info["bone_dag"]
            loc_name = "Goal_{}_{}".format(tag, _sanitize_maya_name(g_name))
            loc = cmds.spaceLocator(name=loc_name)[0]
            loc_dag = cmds.ls(loc, long=True)[0]
            loc_dag = cmds.ls(cmds.parent(loc_dag, goals_grp)[0], long=True)[0]

            pos = pose_mgr.get_aligned_rest_position(b_dag) if pose_mgr else skel.rest_world_pos[b_dag]
            rot = pose_mgr.get_aligned_rest_rotation(b_dag) if pose_mgr else skel.rest_world_rot[b_dag]
            set_world_transform(loc_dag, pos, rot)

            shapes = cmds.listRelatives(loc_dag, shapes=True, fullPath=True) or []
            for s in shapes:
                cmds.setAttr(s + ".localScaleX", loc_scale)
                cmds.setAttr(s + ".localScaleY", loc_scale)
                cmds.setAttr(s + ".localScaleZ", loc_scale)
            _set_wire_color(loc_dag, (1.0, 0.9, 0.1), line_width=2.5)
            _set_outliner_color(loc_dag, (1.0, 0.9, 0.2))

            _add_str_attr(loc_dag, "goalName", g_name)
            _add_str_attr(loc_dag, "boneName", g_info["bone_name"])
            _add_str_attr(loc_dag, "boneDAG", b_dag)
            _add_str_attr(loc_dag, "chainName", g_info["chain_name"])
            _add_float_attr(loc_dag, "positionAlpha", g_info.get("position_alpha", 1.0), keyable=True)
            _add_float_attr(loc_dag, "rotationAlpha", g_info.get("rotation_alpha", 1.0), keyable=True)

            if not cmds.attributeQuery("drivenBone", node=loc_dag, exists=True):
                cmds.addAttr(loc_dag, longName="drivenBone", attributeType="message")
            try:
                cmds.connectAttr(b_dag + ".message", loc_dag + ".drivenBone", force=True)
            except Exception:
                pass

            fbik_solver.register_goal_locator(g_name, loc_dag, b_dag)

        # ----------------------------------------------------------------------
        # 3. Sub-group: FBIKSolverSettings + Register Live FBIK Callbacks & DG Expression
        # ----------------------------------------------------------------------
        fbik_grp = cls._recreate_child_group(
            asset_node_dag, "FBIKSolver_{}".format(tag)
        )
        _add_str_attr(fbik_grp, "solverType", "FIKRigFullBodyIKSolver (Live Interactive)")
        _add_str_attr(fbik_grp, "rootBone", prof["pelvis_bone"])
        _add_str_attr(fbik_grp, "rootBoneDAG", prof["pelvis_bone_dag"])
        _add_str_attr(fbik_grp, "rootBehavior", "PinToInput")
        _add_bool_attr(fbik_grp, "allowStretch", False)

        for b_clean, settings in prof.get("fbik_bone_settings", {}).items():
            b_node_name = "FBIKBone_{}_{}".format(tag, _sanitize_maya_name(b_clean))
            b_node_dag = cls._recreate_child_group(fbik_grp, b_node_name)
            b_dag = skel.resolve_bone_dag(b_clean) or ""
            _add_str_attr(b_node_dag, "boneName", b_clean)
            _add_str_attr(b_node_dag, "boneDAG", b_dag)
            if b_dag and cmds.objExists(b_dag):
                if not cmds.attributeQuery("connectedBone", node=b_node_dag, exists=True):
                    cmds.addAttr(b_node_dag, longName="connectedBone", attributeType="message")
                try:
                    cmds.connectAttr(b_dag + ".message", b_node_dag + ".connectedBone", force=True)
                except Exception:
                    pass
            if "rotation_stiffness" in settings:
                _add_float_attr(b_node_dag, "rotationStiffness", settings["rotation_stiffness"])
            if "preferred_axis" in settings:
                _add_str_attr(b_node_dag, "preferredAnglesAxis", settings["preferred_axis"])
            if "excluded" in settings:
                _add_bool_attr(b_node_dag, "isExcluded", settings["excluded"])

        # Activate real-time Full-Body IK evaluation when dragging any Goal locator
        register_live_fbik_solver(fbik_solver, fbik_grp)

        return asset_node_dag, fbik_solver

    @classmethod
    def _build_rtg_scene_node(cls, parent_dag, rtg_asset, pair_tag, json_path, outliner_rgb):
        asset_node_dag = cls._recreate_child_group(parent_dag, rtg_asset.asset_name)
        _set_outliner_color(asset_node_dag, outliner_rgb)

        proc = rtg_asset.processor
        src_skel = proc.source_skeleton
        tgt_skel = proc.target_skeleton
        tgt_pose = proc.target_pose_mgr
        rtg_dict = rtg_asset.to_dict()

        src_p_h = src_skel.rest_world_pos[proc.source_pelvis].y
        tgt_p_h = tgt_pose.get_aligned_rest_position(proc.target_pelvis).y
        root_off = tgt_pose.root_translation_offset

        _add_str_attr(asset_node_dag, "ueAssetType", "UIKRetargeter (UE 5.8)")
        _add_str_attr(asset_node_dag, "sourceIKRigAsset", rtg_asset.source_ikrig.asset_name)
        _add_str_attr(asset_node_dag, "targetIKRigAsset", rtg_asset.target_ikrig.asset_name)
        _add_float_attr(asset_node_dag, "sourcePelvisHeight", round(src_p_h, 3))
        _add_float_attr(asset_node_dag, "targetPelvisHeight", round(tgt_p_h, 3))
        _add_float_attr(
            asset_node_dag,
            "pelvisHeightRatio",
            round(proc.pelvis_solver.height_ratio if proc.pelvis_solver else 1.0, 4)
        )
        _add_float_attr(asset_node_dag, "snapToGroundOffsetY", round(root_off.y, 4))
        _add_int_attr(asset_node_dag, "mappedChainCount", len(proc.chain_mappings))
        _add_int_attr(asset_node_dag, "alignedBoneDeltaCount", len(tgt_pose.delta_rotations))
        _add_str_attr(
            asset_node_dag,
            "bonesExcludedFromAutoPose",
            ", ".join(getattr(proc, "bones_to_exclude_from_auto_pose", []))
        )
        if json_path:
            _add_str_attr(asset_node_dag, "exportedJsonFile", json_path)

        # 1. Sub-group: RetargetOps_Stack
        ops_grp = cls._recreate_child_group(
            asset_node_dag, "RetargetOps_Stack_{}".format(pair_tag)
        )
        for op in rtg_dict["retarget_ops"]:
            op_short = op["op_type"].replace("FIKRetarget", "")
            op_node_name = "Op{}_{}_{}".format(op["op_index"] + 1, op_short, pair_tag)
            op_node_dag = cls._recreate_child_group(ops_grp, op_node_name)
            _add_str_attr(op_node_dag, "opType", op["op_type"])
            _add_bool_attr(op_node_dag, "enabled", op["enabled"])
            for k, v in op["settings"].items():
                attr_k = _sanitize_maya_name(k)
                if isinstance(v, bool):
                    _add_bool_attr(op_node_dag, attr_k, v)
                elif isinstance(v, int):
                    _add_int_attr(op_node_dag, attr_k, v)
                elif isinstance(v, float):
                    _add_float_attr(op_node_dag, attr_k, v)
                elif isinstance(v, (list, tuple)):
                    _add_str_attr(op_node_dag, attr_k, ", ".join(str(x) for x in v))
                else:
                    _add_str_attr(op_node_dag, attr_k, str(v))

        # 2. Sub-group: ChainMappings
        maps_grp = cls._recreate_child_group(
            asset_node_dag, "ChainMappings_{}".format(pair_tag)
        )
        _add_int_attr(maps_grp, "mappingCount", len(proc.chain_mappings))

        for m in proc.chain_mappings:
            m_node_name = "Map_{}_{}".format(pair_tag, _sanitize_maya_name(m.name))
            m_node_dag = cls._recreate_child_group(maps_grp, m_node_name)
            _add_str_attr(m_node_dag, "chainName", m.name)
            _add_str_attr(
                m_node_dag,
                "sourceBones",
                "{} -> {} ({} bones)".format(
                    src_skel.get_clean_name(m.source_chain.start_bone),
                    src_skel.get_clean_name(m.source_chain.end_bone),
                    len(m.source_chain.bones),
                ),
            )
            _add_str_attr(
                m_node_dag,
                "targetBones",
                "{} -> {} ({} bones)".format(
                    tgt_skel.get_clean_name(m.target_chain.start_bone),
                    tgt_skel.get_clean_name(m.target_chain.end_bone),
                    len(m.target_chain.bones),
                ),
            )
            _add_bool_attr(m_node_dag, "enableFK", m.enable_fk)
            _add_bool_attr(m_node_dag, "enableIK", m.enable_ik)
            _add_str_attr(m_node_dag, "ikGoalName", m.ik_goal_name or "None")
            _add_str_attr(m_node_dag, "rotationMode", m.rotation_mode)
            _add_float_attr(m_node_dag, "rotationAlpha", m.rotation_alpha)

        # 3. Sub-group: TargetRetargetPose_Deltas
        pose_grp = cls._recreate_child_group(
            asset_node_dag, "TargetRetargetPose_{}".format(pair_tag)
        )
        _add_str_attr(pose_grp, "poseName", "DefaultRetargetPose")
        _add_str_attr(
            pose_grp,
            "rootTranslationOffset",
            "({:.3f}, {:.3f}, {:.3f})".format(root_off.x, root_off.y, root_off.z)
        )
        _add_int_attr(pose_grp, "alignedBoneCount", len(tgt_pose.delta_rotations))

        for j_dag in tgt_skel.joint_names:
            if j_dag not in tgt_pose.delta_rotations:
                continue
            w_quat = tgt_pose.delta_rotations[j_dag]
            l_quat = tgt_pose.local_delta_rotations.get(j_dag, om.MQuaternion.kIdentity)
            clean_b = tgt_skel.get_clean_name(j_dag)
            d_node_name = "PoseDelta_{}_{}".format(pair_tag, _sanitize_maya_name(clean_b))
            d_node_dag = cls._recreate_child_group(pose_grp, d_node_name)

            w_deg = _quat_to_deg_list(w_quat)
            l_deg = _quat_to_deg_list(l_quat)
            _add_str_attr(d_node_dag, "boneName", clean_b)
            _add_str_attr(d_node_dag, "boneDAG", j_dag)
            _add_str_attr(
                d_node_dag,
                "worldDeltaEulerDeg",
                "({:.2f}, {:.2f}, {:.2f})".format(w_deg[0], w_deg[1], w_deg[2])
            )
            _add_str_attr(
                d_node_dag,
                "localDeltaEulerDeg",
                "({:.2f}, {:.2f}, {:.2f})".format(l_deg[0], l_deg[1], l_deg[2])
            )
            _add_str_attr(d_node_dag, "worldDeltaQuat", str(_quat_to_list(w_quat)))
            _add_str_attr(d_node_dag, "localDeltaQuat", str(_quat_to_list(l_quat)))

        return asset_node_dag


def _list_to_vec(lst):
    return om.MVector(float(lst[0]), float(lst[1]), float(lst[2]))


def _list_to_quat(lst):
    return om.MQuaternion(float(lst[0]), float(lst[1]), float(lst[2]), float(lst[3])).normal()


class ThreeAssetLoader(object):
    """
    Loads the 3 UE 5.8 Standard Retarget Assets:
      1. IK_AutoGeneratedSource (.ikrig.json)
      2. IK_AutoGeneratedTarget (.ikrig.json)
      3. RTG_AutoGenerated      (.rtg.json)
    back into an active IKRetargetProcessor so Step 2 (Animation Retargeting & Baking)
    uses the exact reference poses, retarget pose deltas, chain mappings, and RetargetOp
    settings captured when the 3 assets were built—completely immune to animation frame pollution.
    """

    @staticmethod
    def apply_three_asset_dicts(processor, src_ikrig_dict, tgt_ikrig_dict, rtg_dict):
        """
        Applies serialized dicts of IK_AutoGeneratedSource, IK_AutoGeneratedTarget,
        and RTG_AutoGenerated onto `processor`.
        """
        from .math_utils import get_world_transform

        src_skel = processor.source_skeleton
        tgt_skel = processor.target_skeleton
        tgt_pose = processor.target_pose_mgr

        # 1. Restore Source A reference pose from IK_AutoGeneratedSource
        if src_ikrig_dict and "skeleton" in src_ikrig_dict:
            bones_list = src_ikrig_dict["skeleton"].get("bones", [])
            by_dag = {b.get("dag_path"): b for b in bones_list if b.get("dag_path")}
            by_clean = {b.get("clean_name"): b for b in bones_list if b.get("clean_name")}
            for j_dag in src_skel.joint_names:
                c_name = src_skel.get_clean_name(j_dag)
                entry = by_dag.get(j_dag) or by_clean.get(c_name)
                if entry:
                    src_skel.rest_world_pos[j_dag] = _list_to_vec(entry["ref_world_pos"])
                    src_skel.rest_world_rot[j_dag] = _list_to_quat(entry["ref_world_rot"])
                    src_skel.rest_local_pos[j_dag] = _list_to_vec(entry["ref_local_pos"])
                    src_skel.rest_local_rot[j_dag] = _list_to_quat(entry["ref_local_rot"])

        # 2. Restore Target B reference pose from IK_AutoGeneratedTarget
        #    (Preserve any horizontal X/Z scene placement offset if the user moved Target B sideways)
        if tgt_ikrig_dict and "skeleton" in tgt_ikrig_dict:
            bones_list = tgt_ikrig_dict["skeleton"].get("bones", [])
            by_dag = {b.get("dag_path"): b for b in bones_list if b.get("dag_path")}
            by_clean = {b.get("clean_name"): b for b in bones_list if b.get("clean_name")}

            curr_tgt_root_pos, _ = get_world_transform(processor.target_root)
            root_c_name = tgt_skel.get_clean_name(processor.target_root)
            root_entry = by_dag.get(processor.target_root) or by_clean.get(root_c_name)
            scene_xz_offset = om.MVector(0.0, 0.0, 0.0)
            if root_entry:
                cached_root_pos = _list_to_vec(root_entry["ref_world_pos"])
                scene_xz_offset = om.MVector(
                    curr_tgt_root_pos.x - cached_root_pos.x,
                    0.0,
                    curr_tgt_root_pos.z - cached_root_pos.z,
                )

            for j_dag in tgt_skel.joint_names:
                c_name = tgt_skel.get_clean_name(j_dag)
                entry = by_dag.get(j_dag) or by_clean.get(c_name)
                if entry:
                    tgt_skel.rest_world_pos[j_dag] = _list_to_vec(entry["ref_world_pos"]) + scene_xz_offset
                    tgt_skel.rest_world_rot[j_dag] = _list_to_quat(entry["ref_world_rot"])
                    tgt_skel.rest_local_pos[j_dag] = _list_to_vec(entry["ref_local_pos"])
                    tgt_skel.rest_local_rot[j_dag] = _list_to_quat(entry["ref_local_rot"])

        # 3. Restore Target B RetargetPose & RetargetOps from RTG_AutoGenerated
        if rtg_dict:
            pose_name = rtg_dict.get("current_target_retarget_pose", "DefaultRetargetPose")
            tgt_poses = rtg_dict.get("target_retarget_poses", {})
            pose_data = tgt_poses.get(pose_name) or next(iter(tgt_poses.values()), {})

            if "root_translation_offset" in pose_data:
                tgt_pose.root_translation_offset = _list_to_vec(pose_data["root_translation_offset"])

            tgt_pose.delta_rotations.clear()
            world_deltas = pose_data.get("bone_rotation_deltas_world", {})
            deltas_by_clean = {v.get("clean_name"): v for v in world_deltas.values() if isinstance(v, dict) and v.get("clean_name")}
            for j_dag in tgt_skel.joint_names:
                c_name = tgt_skel.get_clean_name(j_dag)
                d_entry = world_deltas.get(j_dag) or deltas_by_clean.get(c_name)
                if d_entry and "quat" in d_entry:
                    tgt_pose.delta_rotations[j_dag] = _list_to_quat(d_entry["quat"])

            # Restore RetargetOp flags & PelvisMotionOp settings
            for op in rtg_dict.get("retarget_ops", []):
                op_type = op.get("op_type", "")
                enabled = bool(op.get("enabled", True))
                settings = op.get("settings", {})
                if op_type == "FIKRetargetPelvisMotionOp" and processor.pelvis_solver:
                    processor.pelvis_solver.scale_horizontal = float(settings.get("scale_horizontal", 1.0))
                    processor.pelvis_solver.scale_vertical = float(settings.get("scale_vertical", 1.0))
                    processor.pelvis_solver.blend_to_absolute = float(settings.get("blend_to_absolute", 0.0))
                    processor.pelvis_solver.floor_constraint_weight = float(settings.get("floor_constraint_weight", 1.0))
                elif op_type in ("FIKRetargetIKChainsOp", "FIKRetargetRunIKRigOp"):
                    processor.enable_ik_pass = enabled
                elif op_type == "FIKRetargetAlignPoleVectorOp":
                    processor.enable_pole_vector_op = enabled

        # 4. Recompute chain lengths/parameters and refresh all solvers
        for mapping in processor.chain_mappings:
            mapping.source_chain._build_chain()
            mapping.target_chain._build_chain()

        tgt_pose.recompute_aligned_transforms()
        processor.update_retarget_poses()
        processor._rebuild_asset_definitions()

    @staticmethod
    def load_from_rtg_file(processor, rtg_json_path):
        """
        Loads `RTG_AutoGenerated.rtg.json` from disk, automatically resolves and loads
        its companion `IK_AutoGeneratedSource.ikrig.json` and `IK_AutoGeneratedTarget.ikrig.json`
        files in the same folder, and applies all 3 assets to `processor`.
        """
        with open(rtg_json_path, "r", encoding="utf-8") as f:
            rtg_dict = json.load(f)

        base_dir = os.path.dirname(os.path.abspath(rtg_json_path))
        src_file = rtg_dict.get("source_ik_rig_file") or (rtg_dict.get("source_ik_rig_asset", "") + ".ikrig.json")
        tgt_file = rtg_dict.get("target_ik_rig_file") or (rtg_dict.get("target_ik_rig_asset", "") + ".ikrig.json")

        src_path = os.path.join(base_dir, src_file)
        tgt_path = os.path.join(base_dir, tgt_file)

        src_ikrig_dict = None
        tgt_ikrig_dict = None
        if os.path.exists(src_path):
            with open(src_path, "r", encoding="utf-8") as f:
                src_ikrig_dict = json.load(f)
        if os.path.exists(tgt_path):
            with open(tgt_path, "r", encoding="utf-8") as f:
                tgt_ikrig_dict = json.load(f)

        ThreeAssetLoader.apply_three_asset_dicts(processor, src_ikrig_dict, tgt_ikrig_dict, rtg_dict)
        return {
            "src_ikrig": src_ikrig_dict,
            "tgt_ikrig": tgt_ikrig_dict,
            "rtg": rtg_dict,
            "rtg_path": rtg_json_path,
        }


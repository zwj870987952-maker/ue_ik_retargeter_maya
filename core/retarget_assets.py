"""
UE 5.8 Standard Three-Asset Architecture for Maya:
1. IK_AutoGeneratedSource (.ikrig.json + In-Scene Maya Outliner/Viewport Asset)
2. IK_AutoGeneratedTarget (.ikrig.json + In-Scene Maya Outliner/Viewport Asset)
3. RTG_AutoGenerated      (.rtg.json   + In-Scene Maya Outliner/Viewport Asset)

Features:
- Live DG Chain-to-Bone Binding: Every CV of every 3D BoneChain curve is live-connected
  to its skeleton joint's `.worldMatrix[0]` via `pointMatrixMult` nodes + `.connectedBones`
  message links, so chains deform in real time with the skeleton!
- Live Full-Body IK (FBIK): Moving or rotating any IK Effector Goal locator
  (`LeftHandIK`, `RightHandIK`, `LeftFootIK`, `RightFootIK`, `Pelvis_RootGoal`) in the
  Maya viewport drives the entire body (Pelvis, Spine, Clavicles, Arms, Legs) in real time!
- 100% Immune to Duplicate Joint Names ("注意重名") via full Maya DAG paths.
"""


# -*- coding: utf-8 -*-
"""
[Step 1 Verification] Generate UE 5.8 Standard 3 Assets in Current Maya Scene
  1. IK_AutoGeneratedSource_<SrcTag>
  2. IK_AutoGeneratedTarget_<TgtTag>
  3. RTG_AutoGenerated_<SrcTag>_to_<TgtTag>

Usage:
  1. In your current Maya scene, select Skeleton A (Source) and Skeleton B (Target).
  2. Drag and drop this file into the Maya 3D Viewport, OR run it in Maya's Script Editor.
"""

from launch_in_maya import _resolve_package_parent
import sys
import importlib


def run_generate_three_assets(apply_aligned_pose=True):
    pkg_parent = _resolve_package_parent()
    for mod_name in list(sys.modules.keys()):
        if mod_name == "ue_ik_retargeter_maya" or mod_name.startswith("ue_ik_retargeter_maya."):
            del sys.modules[mod_name]
    if pkg_parent in sys.path:
        sys.path.remove(pkg_parent)
    sys.path.insert(0, pkg_parent)
    importlib.invalidate_caches()

    import ue_ik_retargeter_maya
    return ue_ik_retargeter_maya.generate_retarget_assets(
        build_in_scene=True,
        apply_aligned_pose=apply_aligned_pose,
        hot_reload=True,
    )


def onMayaDroppedPythonFile(*args, **kwargs):
    run_generate_three_assets(apply_aligned_pose=True)


if __name__ == "__main__":
    run_generate_three_assets(apply_aligned_pose=True)
